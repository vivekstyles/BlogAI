-- BlogAI SQL practice database: a small, fictional online shop.
-- Tested on PostgreSQL 18 and SQLite 3.50; uses only standard CREATE TABLE and INSERT statements.
-- All names, emails and orders are invented. Companion to https://blogai.space/articles/sql-queries-for-data-analysts

DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS customers;

CREATE TABLE customers (
  customer_id INTEGER PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  email       VARCHAR(200) NOT NULL,
  country     VARCHAR(60),
  signup_date DATE NOT NULL
);

CREATE TABLE products (
  product_id INTEGER PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  category   VARCHAR(40) NOT NULL,
  price      DECIMAL(10, 2) NOT NULL
);

CREATE TABLE orders (
  order_id    INTEGER PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers (customer_id),
  order_date  DATE NOT NULL,
  status      VARCHAR(20) NOT NULL
);

CREATE TABLE order_items (
  order_id   INTEGER NOT NULL REFERENCES orders (order_id),
  product_id INTEGER NOT NULL REFERENCES products (product_id),
  quantity   INTEGER NOT NULL,
  unit_price DECIMAL(10, 2) NOT NULL,
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE events (
  session_id  VARCHAR(10) NOT NULL,
  customer_id INTEGER,
  event_name  VARCHAR(30) NOT NULL,
  event_time  TIMESTAMP NOT NULL
);

